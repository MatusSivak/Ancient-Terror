public class Rome15Encounter extends AbstractLocationEncounter{

    public Rome15Encounter() {
        super(15, LocationEncounter.LocationEncounterType.ROME);
    }

    @Override
    protected void execute() {
        new SpendSanityTemplate(getTextBuilder(), 2,this::onYes)
                .withFinishAfterSpend(false)
                .execute();
    }

    private void onYes() {
        ServicePlatform.get().getEncounterService().typeFlavor(" \n"+getTextBuilder().withPass().withFlavor().build());
        TypewriterUtils.confirmInfos(getTextBuilder().withPass().withInfo().build()).subscribe(() -> {
            ServicePlatform.get().getEncounterService().hold();
            ServicePlatform.get().getEncounterService().finishTypewriterPaper();
            ServicePlatform.get().getGameService().gainCondition(ConditionId.BLESSED);
            ServicePlatform.get().getEncounterService().release();
        });
    }

}
